-- NextFit database schema for Oracle (one table per CSV file).
-- Run it as ADMIN after: ALTER SESSION SET CURRENT_SCHEMA = NEXTFIT_APP;
-- Notes:
--  * Oracle stores an empty text as NULL, so optional text columns are nullable
--    and the repositories turn NULL back into "".
--  * Booleans are NUMBER(1) with a 0/1 check.
--  * ids are identity columns that also accept explicit values (CSV migration).
--  * "audit" is a reserved word in Oracle, so that table is named audit_log.

CREATE TABLE IF NOT EXISTS users (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(60)  NOT NULL UNIQUE,
    full_name     VARCHAR2(120) NOT NULL,
    password_hash VARCHAR2(200) NOT NULL,
    role          VARCHAR2(30)  NOT NULL,
    active        NUMBER(1)     DEFAULT 1 NOT NULL CHECK (active IN (0, 1))
);

CREATE TABLE IF NOT EXISTS members (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR2(120) NOT NULL,
    document_number   VARCHAR2(30)  NOT NULL UNIQUE,
    phone             VARCHAR2(30),
    email             VARCHAR2(120),
    birth_date        DATE NOT NULL,
    join_date         DATE NOT NULL,
    photo_path        VARCHAR2(300),
    emergency_contact VARCHAR2(200),
    active            NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0, 1))
);

CREATE TABLE IF NOT EXISTS membership_plans (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR2(80) NOT NULL,
    description   VARCHAR2(500),
    duration_days NUMBER(5)    NOT NULL CHECK (duration_days > 0),
    price         NUMBER(12,2) NOT NULL CHECK (price >= 0),
    active        NUMBER(1)    DEFAULT 1 NOT NULL CHECK (active IN (0, 1))
);

CREATE TABLE IF NOT EXISTS subscriptions (
    id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  NUMBER(19) NOT NULL REFERENCES members (id),
    plan_id    NUMBER(19) NOT NULL REFERENCES membership_plans (id),
    start_date DATE NOT NULL,
    end_date   DATE NOT NULL,
    cancelled  NUMBER(1) DEFAULT 0 NOT NULL CHECK (cancelled IN (0, 1))
);

CREATE TABLE IF NOT EXISTS payments (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id NUMBER(19) NOT NULL REFERENCES subscriptions (id),
    member_id       NUMBER(19) NOT NULL REFERENCES members (id),
    paid_at         TIMESTAMP NOT NULL,
    method          VARCHAR2(30) NOT NULL,
    subtotal        NUMBER(12,2) NOT NULL,
    discount_type   VARCHAR2(30),
    discount_value  NUMBER(12,2),
    registered_by   VARCHAR2(60)
);

CREATE TABLE IF NOT EXISTS attendance (
    id        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER(19) NOT NULL REFERENCES members (id),
    check_in  TIMESTAMP NOT NULL,
    check_out TIMESTAMP
);

CREATE TABLE IF NOT EXISTS health_profiles (
    member_id          NUMBER(19) PRIMARY KEY REFERENCES members (id),
    height_cm          NUMBER(5,1),
    blood_type         VARCHAR2(10),
    medical_conditions VARCHAR2(1000),
    allergies          VARCHAR2(1000)
);

CREATE TABLE IF NOT EXISTS measurements (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   NUMBER(19) NOT NULL REFERENCES members (id),
    measured_on DATE NOT NULL,
    weight_kg   NUMBER(6,2),
    waist_cm    NUMBER(6,2),
    chest_cm    NUMBER(6,2),
    hips_cm     NUMBER(6,2)
);

CREATE TABLE IF NOT EXISTS exercises (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR2(100) NOT NULL,
    description  VARCHAR2(1000),
    muscle_group VARCHAR2(30) NOT NULL,
    difficulty   VARCHAR2(30) NOT NULL,
    image_path   VARCHAR2(300)
);

CREATE TABLE IF NOT EXISTS trainers (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR2(120) NOT NULL,
    document_number VARCHAR2(30)  NOT NULL UNIQUE,
    phone           VARCHAR2(30),
    email           VARCHAR2(120),
    birth_date      DATE NOT NULL,
    specialty       VARCHAR2(100),
    photo_path      VARCHAR2(300),
    active          NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0, 1))
);

CREATE TABLE IF NOT EXISTS routines (
    id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR2(100) NOT NULL,
    objective  VARCHAR2(500),
    trainer_id NUMBER(19) REFERENCES trainers (id),
    created_at DATE NOT NULL
);

-- One row per exercise line of a routine; line_no keeps the order inside the day.
CREATE TABLE IF NOT EXISTS routine_lines (
    routine_id   NUMBER(19) NOT NULL REFERENCES routines (id),
    day_index    NUMBER(3)  NOT NULL,
    line_no      NUMBER(5)  NOT NULL,
    day_name     VARCHAR2(60),
    exercise_id  NUMBER(19) NOT NULL REFERENCES exercises (id),
    sets         NUMBER(4),
    repetitions  NUMBER(4),
    rest_seconds NUMBER(5),
    PRIMARY KEY (routine_id, day_index, line_no)
);

CREATE TABLE IF NOT EXISTS assignments (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   NUMBER(19) NOT NULL REFERENCES members (id),
    routine_id  NUMBER(19) NOT NULL REFERENCES routines (id),
    assigned_at DATE NOT NULL,
    status      VARCHAR2(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS training_sessions (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id        NUMBER(19) NOT NULL REFERENCES members (id),
    assignment_id    NUMBER(19) NOT NULL REFERENCES assignments (id),
    day_name         VARCHAR2(60),
    session_date     DATE NOT NULL,
    duration_minutes NUMBER(4),
    notes            VARCHAR2(1000)
);

CREATE TABLE IF NOT EXISTS audit_log (
    id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time TIMESTAMP NOT NULL,
    username   VARCHAR2(60),
    action     VARCHAR2(40) NOT NULL,
    detail     VARCHAR2(1000)
);

CREATE INDEX IF NOT EXISTS idx_subscriptions_member ON subscriptions (member_id);
CREATE INDEX IF NOT EXISTS idx_payments_member      ON payments (member_id);
CREATE INDEX IF NOT EXISTS idx_attendance_member    ON attendance (member_id);
CREATE INDEX IF NOT EXISTS idx_measurements_member  ON measurements (member_id);
CREATE INDEX IF NOT EXISTS idx_assignments_member   ON assignments (member_id);
CREATE INDEX IF NOT EXISTS idx_sessions_member      ON training_sessions (member_id);


-- Face templates for face recognition: several rows per member, and each row
-- holds the 128 numbers of one face vector as comma separated text.
CREATE TABLE IF NOT EXISTS face_templates (
    id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  NUMBER(19) NOT NULL REFERENCES members (id) ON DELETE CASCADE,
    embedding  VARCHAR2(4000) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_face_templates_member ON face_templates (member_id);

