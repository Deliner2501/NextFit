"""Generates the documents that must always match the code:

  docs/layers-diagram.md            package diagram built from the real imports
  docs/integrated-class-diagram.md  class diagrams (Mermaid) by module
  docs/class-catalog.md             table with every class, its type and its role
  docs/class-reference.md           attributes and public methods of every class

Run it from the project root:  python3 docs/tools/generate_docs.py
"""
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import java_model  # noqa: E402

ROOT_PKG = "(root)"
LAYERS = [
    ("PRES", "Presentation layer (JavaFX + AtlantaFX)", ["ui", "ui.billing", "ui.fx"]),
    ("BUS", "Business layer", ["service", "service.alert", "service.audit", "service.churn", "service.face",
                               "service.gamification", "service.occupancy", "service.portal",
                               "service.security", "service.suggest", "validation", "export", "ai",
                               "ai.tools", "web", "vision"]),
    ("DATA", "Persistence layer (CSV and Oracle)", ["persistence", "persistence.jdbc"]),
    ("DOM", "Domain layer and shared code", ["model", "exceptions", "util"]),
]
SHARED = {"model", "exceptions", "util"}

# (title, packages, mode) - mode "full" draws every class, "modules" only the window and its modules
GROUPS = [
    ("Domain model", ["model"], "full"),
    ("Persistence: contracts and CSV", ["persistence"], "full"),
    ("Persistence: Oracle (JDBC)", ["persistence.jdbc"], "full"),
    ("Business services", ["service"], "full"),
    ("Alerts, churn risk and suggestions", ["service.alert", "service.churn", "service.suggest"], "full"),
    ("Face recognition and camera", ["service.face", "vision"], "full"),
    ("Security, audit, occupancy, achievements and portal data",
     ["service.security", "service.audit", "service.occupancy", "service.gamification", "service.portal"], "full"),
    ("Validation, exceptions and helpers", ["validation", "exceptions", "util"], "full"),
    ("AI assistant", ["ai", "ai.tools"], "full"),
    ("Export and web server", ["export", "web"], "full"),
    ("Interface: window and modules", ["ui.fx"], "modules"),
    ("Composition root", [ROOT_PKG], "full"),
]
HEAD = ("<!-- Generated by docs/tools/generate_docs.py from the source code. "
        "Do not edit by hand: run the script again. -->\n\n")


def strip_generics(text):
    return re.sub(r"<.*>", "", text).replace("[]", "").strip()


def mermaid_type(text):
    return text.replace("<", "~").replace(">", "~").replace("?", "").replace(",", ", ").replace("  ", " ")


def is_getter(method):
    return re.match(r"^(get|is|has)[A-Z]", method.name) is not None


def layer_of(pkg):
    for key, _, pkgs in LAYERS:
        if pkg in pkgs:
            return key
    return "ROOT"


def group_by_package(types):
    by_pkg = collections.defaultdict(list)
    for t in types:
        by_pkg[t.package].append(t)
    return by_pkg


def import_graph(types):
    deps = collections.defaultdict(set)
    for t in types:
        source = open(t.file, encoding="utf-8").read()
        for m in re.finditer(r"^import (?:static )?com\.nextfit\.([\w.]*?)\.?([A-Z]\w*)[;.]", source, re.M):
            pkg = m.group(1) or ROOT_PKG
            if pkg != t.package:
                deps[t.package].add(pkg)
    return deps


def package_order():
    return [ROOT_PKG] + [p for _, _, plist in LAYERS for p in plist]


def write_layers(types, out):
    pkgs = group_by_package(types)
    deps = import_graph(types)
    node = lambda p: "P_" + re.sub(r"\W", "_", p)
    lines = [HEAD, "# Layers and Package Diagram\n\n",
             "NextFit follows a layered architecture. Each arrow means \"depends on\" and it comes from the real "
             "`import` statements of the code (the number is how many classes each package has). Dependencies "
             "only go downwards: the interface never touches the persistence, and the domain depends on nothing "
             "but its exceptions. Every package also uses `model` and `exceptions`; those arrows are not drawn "
             "so the diagram stays readable.\n\n",
             "## Package diagram by layers\n\n```mermaid\ngraph TD\n",
             '    subgraph ROOT["com.nextfit - Composition root"]\n',
             f'        {node(ROOT_PKG)}["<b>nextfit</b><br/>Main, DemoData, StorageSetup<br/>({len(pkgs[ROOT_PKG])} classes)"]\n',
             "    end\n"]
    for key, title, plist in LAYERS:
        lines.append(f'    subgraph {key}["{title}"]\n')
        for p in plist:
            if p in pkgs:
                lines.append(f'        {node(p)}["<b>{p}</b><br/>({len(pkgs[p])} {"class" if len(pkgs[p]) == 1 else "classes"})"]\n')
        lines.append("    end\n")
    drawn = set()
    cross = set()
    for src in sorted(deps):
        for dst in sorted(deps[src]):
            if dst in SHARED or dst not in pkgs or src not in pkgs:
                continue
            drawn.add((src, dst))
            if layer_of(src) == layer_of(dst):
                lines.append(f"    {node(src)} --> {node(dst)}\n")
            elif layer_of(src) != "ROOT":
                cross.add((layer_of(src), layer_of(dst)))
    cross |= {("PRES", "DOM"), ("BUS", "DOM"), ("DATA", "DOM")}
    for src, dst in sorted(cross):
        lines.append(f"    {src} ==> {dst}\n")
    for key, _, _ in LAYERS:
        lines.append(f"    ROOT -.-> {key}\n")
    lines.append("```\n\n")
    lines.append("Thick arrows are dependencies between layers (they group the arrows between their packages); thin "
                 "arrows are dependencies between packages of the same layer; dotted arrows show that the composition "
                 "root creates the objects of every layer.\n\n")
    order = {"PRES": 0, "BUS": 1, "DATA": 2, "DOM": 3}
    upward = sorted((s, d) for s, d in drawn
                    if layer_of(s) in order and layer_of(d) in order and order[layer_of(s)] > order[layer_of(d)])
    lines.append("## Dependency rule\n\n")
    if not upward:
        lines.append("Checked against the imports: **no package depends on a higher layer.** The only package that "
                     "knows every layer is the composition root (`Main`), which builds the objects and injects them.\n\n")
    else:
        lines.append("Dependencies that go upwards (to review): "
                     + ", ".join(f"`{s}` -> `{d}`" for s, d in upward) + "\n\n")
    lines.append("## Layers and responsibilities\n\n| Layer | Packages | Responsibility |\n|---|---|---|\n")
    resp = {
        "PRES": "Shows data and collects what the user does. It never reads files or the database: it asks the services.",
        "BUS": "Business rules, validation, use cases, reports, face recognition, the assistant and the phone server.",
        "DATA": "Repository interfaces and their two implementations: CSV files and Oracle through JDBC.",
        "DOM": "Entities, enums and value objects with no dependencies, plus the exceptions and small helpers.",
    }
    for key, title, plist in LAYERS:
        lines.append(f"| {title} | " + ", ".join(f"`{p}`" for p in plist if p in pkgs) + f" | {resp[key]} |\n")
    lines.append("| Composition root | `nextfit` | `Main` builds every object and injects the dependencies "
                 "(Creator and Dependency Inversion). |\n")
    open(out, "w", encoding="utf-8").write("".join(lines))


def class_block(t):
    lines = [f"    class {t.name} {{\n"]
    if t.kind == "interface":
        lines.append("        <<interface>>\n")
    elif t.kind == "enum":
        lines.append("        <<enumeration>>\n")
    elif t.abstract:
        lines.append("        <<abstract>>\n")
    for constant in t.constants[:8]:
        lines.append(f"        {constant}\n")
    for f in t.fields[:5]:
        lines.append(f"        -{mermaid_type(f.type)} {f.name}\n")
    for m in [m for m in t.methods if not is_getter(m)][:5]:
        lines.append(f"        +{m.name}()\n")
    lines.append("    }\n")
    return "".join(lines)


def write_diagrams(types, out):
    by_pkg = group_by_package(types)
    known = {t.name for t in types}
    lines = [HEAD, "# Integrated Class Diagram\n\n",
             "All the classes of the system, split by module so each diagram can be read. They come from the source "
             "code: a hollow triangle is inheritance (solid line) or interface implementation (dotted line), and an "
             "arrow means that the class keeps the other one in an attribute. Every class and its role is in the "
             "[class catalog](class-catalog.md); attributes and methods are in the "
             "[class reference](class-reference.md). A diagram shows up to five attributes and five methods per class.\n\n"]
    for title, pkglist, mode in GROUPS:
        group = [t for p in pkglist for t in by_pkg.get(p, [])]
        if not group:
            continue
        if mode == "modules":
            modules = [t for t in group if "FxModule" in t.implements]
            core = [t for t in group if t.name in ("FxModule", "FxApp", "ShellView", "LoginView")]
            shown = sorted({t.name: t for t in modules + core}.values(), key=lambda t: t.name)
            note = (f"The package has {len(group)} classes. The diagram shows the window and the {len(modules)} modules "
                    "that implement `FxModule`; the panes, forms and helpers of each module are in the catalog.")
        else:
            shown = sorted(group, key=lambda t: t.name)
            note = f"{len(group)} classes."
        names = {t.name for t in shown}
        lines.append(f"## {title}\n\n{note}\n\n```mermaid\nclassDiagram\n    direction TB\n")
        for t in shown:
            if mode == "modules":
                if t.kind == "interface":
                    lines.append(f"    class {t.name} {{\n        <<interface>>\n    }}\n")
                else:
                    lines.append(f"    class {t.name}\n")
            else:
                lines.append(class_block(t))
        seen = set()
        for t in shown:
            for parent, arrow, interface in [(p, "<|--", False) for p in t.extends] + \
                                            [(p, "<|..", True) for p in t.implements]:
                if parent not in known or (parent, t.name, arrow) in seen:
                    continue
                seen.add((parent, t.name, arrow))
                if parent not in names:
                    names.add(parent)
                    lines.append(f"    class {parent} {{\n        <<interface>>\n    }}\n" if interface
                                 else f"    class {parent}\n")
                lines.append(f"    {parent} {arrow} {t.name}\n")
            if mode == "modules":
                continue
            for f in t.fields:
                target = re.sub(r".*<(.*)>.*", r"\1", f.type) if "<" in f.type else f.type
                target = strip_generics(target).split(",")[-1].strip()
                if target in names and target != t.name and (t.name, target, "-->") not in seen \
                        and (target, t.name, "<|--") not in seen and (target, t.name, "<|..") not in seen:
                    seen.add((t.name, target, "-->"))
                    lines.append(f"    {t.name} --> {target}\n")
        lines.append("```\n\n")
    open(out, "w", encoding="utf-8").write("".join(lines))


def write_catalog(types, out):
    by_pkg = group_by_package(types)
    lines = [HEAD, "# Class Catalog\n\n",
             f"{len(types)} classes, interfaces, records and enums, by package. The type comes from the declaration "
             "and the role from the Javadoc of each class.\n\n| Type | Count |\n|---|--:|\n"]
    for label, count in collections.Counter(t.label for t in types).most_common():
        lines.append(f"| {label} | {count} |\n")
    lines.append("\n")
    number = 0
    for pkg in package_order():
        group = sorted(by_pkg.get(pkg, []), key=lambda t: t.name)
        if not group:
            continue
        lines.append(f"## `{'com.nextfit' if pkg == ROOT_PKG else 'com.nextfit.' + pkg}`\n\n"
                     "| # | Class | Type | Role in the system |\n|--:|---|---|---|\n")
        for t in group:
            number += 1
            lines.append(f"| {number} | `{t.name}` | {t.label} | {t.doc.replace('|', '/') or '-'} |\n")
        lines.append("\n")
    open(out, "w", encoding="utf-8").write("".join(lines))


def write_reference(types, out):
    by_pkg = group_by_package(types)
    lines = [HEAD, "# Class Reference\n\nFor each class: its responsibility, its attributes and its public methods. "
             "Getters are grouped in one line. It is generated from the source code.\n\n"]
    for pkg in package_order():
        group = sorted(by_pkg.get(pkg, []), key=lambda t: t.name)
        if not group:
            continue
        lines.append(f"## `{'com.nextfit' if pkg == ROOT_PKG else 'com.nextfit.' + pkg}`\n\n")
        for t in group:
            relations = []
            if t.extends:
                relations.append("extends " + ", ".join(f"`{e}`" for e in t.extends))
            if t.implements:
                relations.append("implements " + ", ".join(f"`{e}`" for e in t.implements))
            suffix = f" ({'; '.join(relations)})" if relations else ""
            lines.append(f"### {t.name}\n\n**Type:** {t.label}{suffix}  \n**Responsibility:** {t.doc or '-'}\n\n")
            if t.constants:
                lines.append("**Values:** " + ", ".join(f"`{c}`" for c in t.constants) + "\n\n")
            if t.fields:
                lines.append("| Attribute | Type |\n|---|---|\n")
                for f in t.fields:
                    lines.append(f"| `{f.name}` | `{f.type.replace('|', '/')}` |\n")
                lines.append("\n")
            getters = [m.name for m in t.methods if is_getter(m)]
            others = [m for m in t.methods if not is_getter(m)]
            if others or getters:
                lines.append("| Method | Returns | Description |\n|---|---|---|\n")
                for m in others:
                    lines.append(f"| `{m.name}({m.params.replace('|', '/')})` | `{m.type.replace('|', '/')}` "
                                 f"| {m.doc.replace('|', '/') or '-'} |\n")
                if getters:
                    lines.append("| " + ", ".join(f"`{g}`" for g in getters) + " | - | Getters. |\n")
                lines.append("\n")
    open(out, "w", encoding="utf-8").write("".join(lines))


def main():
    types = java_model.load()
    write_layers(types, os.path.join("docs", "layers-diagram.md"))
    write_diagrams(types, os.path.join("docs", "integrated-class-diagram.md"))
    write_catalog(types, os.path.join("docs", "class-catalog.md"))
    write_reference(types, os.path.join("docs", "class-reference.md"))
    print(f"{len(types)} types written")


if __name__ == "__main__":
    main()
